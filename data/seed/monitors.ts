import type {
  Monitor,
  MonitorPanel,
  MonitorResolution,
} from '../../backend/domain/types';

function monitor(
  id: string,
  brand: string,
  name: string,
  price: number,
  resolution: MonitorResolution,
  panel: MonitorPanel,
  refreshRate: number,
  size: number,
  source?: string,
  refreshRateNote?: string,
): Monitor {
  return {
    id,
    brand,
    name,
    price,
    specs: {
      resolution,
      panel,
      refreshRate,
      size,
      ...(source ? { source, checkedAt: '2026-09-12' } : {}),
      ...(refreshRateNote ? { refreshRateNote } : {}),
      priceBasis: 'merchant-authored',
    },
    demo: false,
  };
}

